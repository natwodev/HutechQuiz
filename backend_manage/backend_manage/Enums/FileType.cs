namespace backend_manage.Enums;

/// <summary>
/// Enum định nghĩa các loại file trong hệ thống
/// </summary>
public enum FileType
{
    Audio,      // 0 - File âm thanh (mp3, wav, etc.)
    Image,      // 1 - File hình ảnh (jpg, png, gif, etc.)
    Document,   // 2 - File tài liệu (pdf, doc, docx, etc.)
    Video,      // 3 - File video (mp4, avi, etc.)
    Other       // 4 - File khác
} 